import fs from 'fs';
import path from 'path';

const distHtmlPath = path.resolve('dist/index.html');
const outputPath = path.resolve('embeddedHtml.js');

if (fs.existsSync(distHtmlPath)) {
  const html = fs.readFileSync(distHtmlPath, 'utf8');
  const content = `// Auto-generated by scripts/generate-embedded-html.js
export const embeddedHtml = ${JSON.stringify(html)};
`;
  fs.writeFileSync(outputPath, content, 'utf8');
  console.log(`Embedded HTML generated successfully (${html.length} bytes)`);
} else {
  console.error('dist/index.html not found! Run npm run build first.');
}
